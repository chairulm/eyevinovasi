"""MediaMTX re-stream config, generated from the camera list.

Each HLS camera becomes a MediaMTX path that pulls the upstream playlist **on demand**
(only while someone is watching or a job reads it) and re-serves it:
  viewers   -> nginx /live/<path>/index.m3u8 -> MediaMTX HLS (127.0.0.1:8888)
  analytics -> rtsp://127.0.0.1:8554/<path>   (local only)
So every camera is pulled from the agency once, however many viewers there are.

MediaMTX watches its config file and reloads it automatically when it changes, so the
collector only has to rewrite the file; nothing needs restarting.

  python -m restream.config            # write data/mediamtx.yml from the current store
"""
from __future__ import annotations

import logging
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = Path(os.getenv("MEDIAMTX_CONFIG", ROOT / "data" / "mediamtx.yml"))
ENABLED = os.getenv("RESTREAM", "0") == "1"
LIVE_PREFIX = "/live"

# Sources whose HLS carries extra tracks MediaMTX's native HLS reader rejects
# (Jogja's Wowza adds an ID3/data track -> "unsupported track type: *mpegts.Track").
# For these, MediaMTX starts ffmpeg on demand, which copies only the video track
# (no re-encode) and publishes it locally over RTSP.
FFMPEG_SOURCES = set(filter(None, os.getenv("RESTREAM_FFMPEG_SOURCES", "jogja").split(",")))
FFMPEG = os.getenv("FFMPEG_BIN", "ffmpeg")
log = logging.getLogger("restream")

GLOBAL = """\
# Generated by restream/config.py — do not edit by hand (it is rewritten after each scrape).
logLevel: warn
logDestinations: [stdout]
readTimeout: 15s
writeTimeout: 15s

api: yes
apiAddress: 127.0.0.1:9997
metrics: no
pprof: no
playback: no

rtsp: yes
rtspAddress: 127.0.0.1:8554
protocols: [tcp]
rtmp: no
srt: no
webrtc: no

hls: yes
hlsAddress: 127.0.0.1:8888
hlsAlwaysRemux: no
hlsVariant: mpegts
hlsSegmentCount: 7
hlsSegmentDuration: 1s
hlsAllowOrigin: '*'

paths:
"""


def path_name(cam_id: str) -> str:
    """'binamarga:its-CT-01' -> 'binamarga_its-CT-01' (MediaMTX-safe, stable)."""
    return re.sub(r"[^A-Za-z0-9_.~-]+", "_", cam_id)


def live_url(cam: dict) -> str | None:
    if not ENABLED or cam.get("playback") != "hls" or not cam.get("stream_url"):
        return None
    return f"{LIVE_PREFIX}/{path_name(cam['id'])}/index.m3u8"


def _yaml_str(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def render(cams: list[dict]) -> str:
    out = [GLOBAL]
    n = 0
    for c in sorted(cams, key=lambda x: x["id"]):
        if c.get("playback") != "hls" or not c.get("stream_url"):
            continue
        name = path_name(c["id"])
        if c.get("source") in FFMPEG_SOURCES:
            cmd = (f"{FFMPEG} -nostdin -loglevel error -user_agent Mozilla/5.0 "
                   f"-i {c['stream_url']} -map 0:v:0 -c copy "
                   f"-f rtsp -rtsp_transport tcp rtsp://127.0.0.1:8554/$MTX_PATH")
            out.append(f"  {name}:\n"
                       f"    runOnDemand: {_yaml_str(cmd)}\n"
                       f"    runOnDemandRestart: yes\n"
                       f"    runOnDemandStartTimeout: 25s\n"
                       f"    runOnDemandCloseAfter: 30s\n")
        else:
            out.append(f"  {name}:\n"
                       f"    source: {_yaml_str(c['stream_url'])}\n"
                       f"    sourceOnDemand: yes\n"
                       f"    sourceOnDemandStartTimeout: 25s\n"
                       f"    sourceOnDemandCloseAfter: 30s\n")
        n += 1
    if not n:
        out.append("  {}\n")
    return "".join(out)


def write(cams: list[dict], path: Path = CONFIG) -> bool:
    """Write the config only if it changed (avoids needless MediaMTX reloads)."""
    text = render(cams)
    if path.exists() and path.read_text() == text:
        return False
    tmp = path.with_suffix(".tmp")
    tmp.write_text(text)
    tmp.replace(path)          # atomic swap so MediaMTX never reads a half-written file
    log.info("mediamtx config updated: %s", path)
    return True


def main():
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s")
    from db.store import get_store
    cams = get_store().list_cameras(include_hidden=True, raw=True)
    changed = write(cams)
    print(f"{CONFIG}: {sum(1 for c in cams if c.get('playback') == 'hls' and c.get('stream_url'))} "
          f"paths ({'updated' if changed else 'unchanged'})")


if __name__ == "__main__":
    main()
